import esbuild from 'esbuild';
import process from 'node:process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { builtinModules } from 'node:module';
import { copyFile, mkdir, rm, readFile } from 'node:fs/promises';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD.
To view the source, visit the plugin's GitHub repository.
*/`;

const production = process.argv[2] === 'production';
const packageJson = JSON.parse(
	await readFile(path.join(ROOT, 'package.json'), 'utf8')
);

const outputDir = path.join(ROOT, 'build', packageJson.name);

// Node.js built-in modules should not be bundled.
const nodeBuiltins = [
	...new Set([
		...builtinModules,
		...builtinModules.map((name) => `node:${name}`)
	])
];

const external = [
	'obsidian',
	'electron',

	// CodeMirror
	'@codemirror/autocomplete',
	'@codemirror/collab',
	'@codemirror/commands',
	'@codemirror/language',
	'@codemirror/lint',
	'@codemirror/search',
	'@codemirror/state',
	'@codemirror/view',

	// Lezer
	'@lezer/common',
	'@lezer/highlight',
	'@lezer/lr',

	...nodeBuiltins
];

const buildOptions = {
	absWorkingDir: ROOT,
	entryPoints: {
		main: 'src/main.ts',
		styles: 'src/styles.css'
	},
	outdir: outputDir,
	bundle: true,
	platform: 'browser',
	format: 'cjs',
	target: 'es2021',
	alias: {
		'@': path.join(ROOT, 'src')
	},
	external,
	banner: {
		js: banner
	},
	sourcemap: production ? false : 'inline',
	minify: production,
	treeShaking: true,
	logLevel: 'info'
};

async function prepareOutput() {
	await rm(outputDir, {
		recursive: true,
		force: true
	});

	await mkdir(outputDir, {
		recursive: true
	});

	await Promise.all([
		copyFile(
			path.join(ROOT, 'manifest.json'),
			path.join(outputDir, 'manifest.json')
		),
		copyFile(
			path.join(ROOT, 'LICENSE'),
			path.join(outputDir, 'LICENSE')
		)
	]);
}

async function build() {
	await prepareOutput();

	if (production) {
		await esbuild.build(buildOptions);
		return;
	}

	const context = await esbuild.context(buildOptions);

	try {
		await context.watch();
	} catch (error) {
		await context.dispose();
		throw error;
	}
}

await build();
